// Publishes the compiled Server into dist/ so the scheduled task runs build artifacts.
//   node node_modules/typescript/bin/tsc && node scripts/publish-server.mjs
//
// What this adds to dist/ (all of it gitignored):
//   scripts/            the launcher, the installer and the two registration requesters
//   .env.local-server   paths only, no credentials (created once, never overwritten)
//   package.json        {"type":"module"} so the compiled ESM runs from here
//
// Why dist/ itself: the installer and the launcher expect <ServerDir>/apps/server/src/main.js and
// <ServerDir>/scripts/*.ps1, and node resolves runtime dependencies by walking up to the checkout's
// node_modules. Publishing in place keeps that contract without copying dependencies.
//
// It also writes a pointer at %LOCALAPPDATA%\MnemoWeave\local-server.json. Three host plugins are
// installed from three different folders; the pointer is what makes them agree on this one
// directory, so they register one task instead of one each.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join, resolve } from 'node:path';

const root = resolve(process.cwd());
const dist = join(root, 'dist');
const main = join(dist, 'apps/server/src/main.js');
if (!existsSync(main)) throw new Error(`compiled Server not found: ${main}\nrun node node_modules/typescript/bin/tsc first`);

const scripts = [
  'run-local-server.ps1',
  'install-local-server-task.ps1',
  'request-registration.ps1',
  'request-registration-task.ps1',
  'local-server.env.example',
];
mkdirSync(join(dist, 'scripts'), { recursive: true });
for (const file of scripts) {
  const source = join(root, 'scripts', file);
  if (!existsSync(source)) throw new Error(`missing script: ${source}`);
  copyFileSync(source, join(dist, 'scripts', file));
}

writeFileSync(join(dist, 'package.json'), `${JSON.stringify({ name: 'mnemoweave-server', private: true, type: 'module' }, null, 2)}\n`);

// The environment file holds paths only. Credentials stay in the signed-in user environment,
// which is the single source the installer, the launcher and every host plugin read.
const envFile = join(dist, '.env.local-server');
if (!existsSync(envFile)) {
  const npmMnemon = join(process.env.APPDATA ?? '', 'npm/node_modules/@mnemon-dev/mnemon/node_modules/@mnemon-dev/mnemon-win32-x64/bin/mnemon.exe');
  const binary = process.env.MNEMON_BINARY?.trim() || (existsSync(npmMnemon) ? npmMnemon : 'mnemon');
  const lines = [
    '# Generated by scripts/publish-server.mjs. Paths only: no token is stored here.',
    '# MNEMOWEAVE_TOKEN and MNEMOWEAVE_OPERATOR_TOKEN come from the signed-in user environment;',
    '# install-local-server-task.ps1 creates them on first registration.',
    `MNEMON_BINARY=${binary}`,
    'MNEMON_DATA_DIR=data/mnemon',
    'MNEMON_STORE=local',
    'MNEMOWEAVE_STATE_DIR=data/state',
    'MNEMOWEAVE_PORT=4317',
    'MNEMOWEAVE_WORKER=on',
    '',
  ];
  writeFileSync(envFile, lines.join('\r\n'));
  process.stdout.write(`created ${envFile}\n`);
} else {
  process.stdout.write(`kept ${envFile}\n`);
}

const localAppData = process.env.LOCALAPPDATA?.trim();
if (localAppData) {
  const pointerDir = join(localAppData, 'MnemoWeave');
  mkdirSync(pointerDir, { recursive: true });
  const pointer = join(pointerDir, 'local-server.json');
  const payload = {
    serverDir: dist,
    envFile,
    nodeExe: process.execPath,
    publishedAt: new Date().toISOString(),
  };
  writeFileSync(pointer, `${JSON.stringify(payload, null, 2)}\n`);
  process.stdout.write(`wrote ${pointer}\n`);
} else {
  process.stdout.write('LOCALAPPDATA is not set; no pointer written (hosts cannot find this publish)\n');
}

// A stale token check is deliberately absent: the installer generates tokens into the user
// environment, and the profile that points a host plugin at the Server must use the same value.
// Reading it back here would copy a credential into a file.
const envText = readFileSync(envFile, 'utf8');
for (const key of ['MNEMOWEAVE_TOKEN', 'MNEMOWEAVE_OPERATOR_TOKEN']) {
  if (envText.includes(`${key}=`)) process.stdout.write(`warning: ${envFile} contains ${key}; credentials belong in the user environment\n`);
}
process.stdout.write(`published ${dist}\n`);

// Registration is the install step, and the only place that asks for elevation: one prompt here,
// then the logon task starts the Server on every sign-in without asking again. A missing task is
// reported by the host plugins as `task_missing`; they never raise the prompt themselves.
const TASK = 'MnemoWeave Local Server';
const taskExists = () => spawnSync('schtasks', ['/query', '/tn', TASK], { stdio: 'ignore' }).status === 0;
const register = process.argv.includes('--register');

if (!taskExists()) {
  if (!register) {
    process.stdout.write(`task "${TASK}" is not registered.\nrun: node scripts/publish-server.mjs --register   (one elevation prompt)\n`);
  } else {
    process.stdout.write(`requesting registration of "${TASK}" through the scheduler; approve the prompt once\n`);
    const resultFile = join(dist, '.registration-result.json');
    const launcher = join(dist, 'scripts', 'request-registration-task.ps1');
    const outcome = spawnSync('powershell.exe', [
      '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', launcher,
      '-ServerDir', dist, '-EnvFile', envFile, '-ResultFile', resultFile,
    ], { stdio: 'inherit' });
    if (taskExists()) {
      spawnSync('schtasks', ['/run', '/tn', TASK], { stdio: 'inherit' });
      process.stdout.write(`registered "${TASK}"\n`);
    } else {
      let detail = '';
      try { detail = readFileSync(resultFile, 'utf8').trim(); } catch { detail = `launcher exit ${String(outcome.status)}`; }
      process.stdout.write(`registration failed: ${detail}\n`);
      process.exitCode = 1;
    }
  }
} else {
  process.stdout.write(`task "${TASK}" is already registered\n`);
}
